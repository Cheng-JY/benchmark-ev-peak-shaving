"""Household profile export for the current building-based scenario workflow."""

import numpy as np
import pandas as pd

from ecv2g.db_api.mongodb import get_task_document

class HouseholdProfileBuilder:
    """Represent household profile builder and its associated operations."""
    def __init__(self, scenario_data, scenario_config):
        """Initialize the instance using the supplied configuration and data.
        
        Parameters
        ----------
        scenario_data : object
            Scenario data used by this operation.
        scenario_config : object
            Scenario config used by this operation."""
        self.scenario_data = scenario_data
        self.household_dir = scenario_data.household_dir
        self.cfg = scenario_config
    
    def build(
        self,
        net_pop_data=None,
        household_ratio: float = 1.0,
        profile=None,
        output_filename: str = "household_load.csv",
    ):
        """Save the BDEW profile generated by the current scenario workflow.

        ``net_pop_data`` remains in the signature only for compatibility with
        older callers. The workflow already creates the station-scaled
        ``hh_profile`` and stores it in ``scenario_tasks``.
        """
        if household_ratio <= 0:
            raise ValueError("household_ratio must be greater than zero")
        if not output_filename.lower().endswith(".csv"):
            raise ValueError("output_filename must end with '.csv'")

        if profile is None:
            scenario_hash = getattr(self.cfg, "scenario_hash", None)
            if not scenario_hash:
                raise ValueError(
                    "No profile supplied and cfg.scenario_hash is empty."
                )
            document = get_task_document({"scenario_hash": scenario_hash})
            if document is None or "hh_profile" not in document:
                raise KeyError(
                    f"No hh_profile found for scenario hash {scenario_hash!r}."
                )
            profile = document["hh_profile"]

        values = np.asarray(profile, dtype=float).reshape(-1) * household_ratio
        if values.size == 0 or not np.isfinite(values).all():
            raise ValueError("hh_profile is empty or contains invalid values")

        time_index = pd.date_range(
            "2012-01-01", periods=len(values), freq="15min"
        )

        df = pd.DataFrame({
            "time": time_index.strftime("%Y-%m-%d %H:%M"),
            "hh_load (MW)": values,
        })

        fp = self.household_dir / output_filename
        df.to_csv(fp, sep=";", index=False)

        return df
